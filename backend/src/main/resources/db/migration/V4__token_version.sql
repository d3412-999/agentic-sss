-- =============================================================================
-- V4：用户令牌版本从 Redis 迁到 MySQL。
--
-- 旧实现把 token_version 存在 Redis：Redis 被 flush、换实例或从旧快照恢复后
-- 版本号会归零，于是「改密码 / 教师重置密码 / 强制下线」吊销过的令牌全部重新
-- 有效，安全语义直接丢失。迁到 sys_user 后版本号与用户同生共死，且递增与比较
-- 都走 DB，天然具备持久性。
--
-- Redis 现在只保留刷新令牌一次性轮换与访问令牌黑名单（可容忍丢失，最坏是
-- 已登出的 accessToken 在剩余有效期内重新可用，而版本校验会兜住密码变更）。
-- =============================================================================

ALTER TABLE sys_user
    ADD COLUMN token_version BIGINT NOT NULL DEFAULT 0 COMMENT '令牌版本：递增即吊销该用户所有已签发令牌' AFTER must_change_password;
